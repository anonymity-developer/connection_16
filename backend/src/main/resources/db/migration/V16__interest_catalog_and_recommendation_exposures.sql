CREATE TABLE recommendation_exposures (
 viewer_id BIGINT NOT NULL,
 batch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 peer_id BIGINT NOT NULL,
 shown_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(viewer_id,batch_id,peer_id),
 INDEX ix_recommendation_recent(viewer_id,peer_id,shown_at),
 INDEX ix_recommendation_retention(viewer_id,shown_at),
 CONSTRAINT fk_exposure_viewer FOREIGN KEY(viewer_id) REFERENCES users(id),
 CONSTRAINT fk_exposure_peer FOREIGN KEY(peer_id) REFERENCES users(id),
 CONSTRAINT ck_exposure_not_self CHECK(viewer_id<>peer_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
